create table if not exists public.pdfs (id bigint generated by default as identity primary key,name text not null,category text not null default 'OTHER',year text,file_url text not null,telegram_file_id text,created_at timestamptz default now());
alter table public.pdfs enable row level security;
create policy "public read" on public.pdfs for select using (true);
insert into storage.buckets (id,name,public) values ('pdfs','pdfs',true) on conflict (id) do nothing;
create policy "public pdf read" on storage.objects for select using (bucket_id='pdfs');
